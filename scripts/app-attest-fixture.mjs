// Regenerates src/server/app-attest/fixtures/attestation.json: an App Attest attestation object
// signed by a made-up CA chain (root → intermediate → P-256 credential certificate), built the way
// Apple builds one, for app-attest.test.ts. Needs the openssl CLI. Test keys only; nothing here is
// trusted outside the tests (they pass the fixture's root instead of Apple's).
//   node scripts/app-attest-fixture.mjs
import { execFileSync } from "node:child_process"
import { createHash, createPrivateKey } from "node:crypto"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { encodeCBOR } from "@levischuck/tiny-cbor"

const OUT = path.resolve("src/server/app-attest/fixtures/attestation.json")
const APP_ID = "ABCDE12345.space.yardstore.app"
const CHALLENGE = "fixture-challenge-0123456789abcdef"
const sha = (b) => createHash("sha256").update(b).digest()

const dir = mkdtempSync(path.join(tmpdir(), "app-attest-fixture-"))
const f = (n) => path.join(dir, n)
const ssl = (...args) => execFileSync("openssl", args, { cwd: dir, stdio: ["ignore", "pipe", "pipe"] })

try {
  ssl("ecparam", "-name", "secp384r1", "-genkey", "-noout", "-out", f("root.key"))
  ssl("req", "-x509", "-new", "-key", f("root.key"), "-subj", "/CN=Test App Attestation Root CA/O=Yard Tests", "-days", "36500", "-set_serial", "1", "-addext", "basicConstraints=critical,CA:TRUE", "-addext", "keyUsage=critical,keyCertSign,cRLSign", "-out", f("root.pem"))
  ssl("ecparam", "-name", "secp384r1", "-genkey", "-noout", "-out", f("inter.key"))
  ssl("req", "-new", "-key", f("inter.key"), "-subj", "/CN=Test App Attestation CA 1/O=Yard Tests", "-out", f("inter.csr"))
  writeFileSync(f("inter.ext"), "basicConstraints=critical,CA:TRUE,pathlen:0\nkeyUsage=critical,keyCertSign,cRLSign\n")
  ssl("x509", "-req", "-in", f("inter.csr"), "-CA", f("root.pem"), "-CAkey", f("root.key"), "-set_serial", "2", "-days", "36500", "-extfile", f("inter.ext"), "-out", f("inter.pem"))

  ssl("ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", f("leaf.ec"))
  ssl("pkcs8", "-topk8", "-nocrypt", "-in", f("leaf.ec"), "-out", f("leaf.key"))
  const leafKey = createPrivateKey(readFileSync(f("leaf.key")))
  const jwk = leafKey.export({ format: "jwk" })
  const point = Buffer.concat([Buffer.from([4]), Buffer.from(jwk.x, "base64url"), Buffer.from(jwk.y, "base64url")])
  const keyHash = sha(point)

  const cose = Buffer.from(encodeCBOR(new Map([[1, 2], [3, -7], [-1, 1], [-2, new Uint8Array(Buffer.from(jwk.x, "base64url"))], [-3, new Uint8Array(Buffer.from(jwk.y, "base64url"))]])))
  const len = Buffer.alloc(2)
  len.writeUInt16BE(keyHash.length)
  const authData = Buffer.concat([sha(APP_ID), Buffer.from([0x40]), Buffer.alloc(4), Buffer.from("appattestdevelop"), len, keyHash, cose])
  const nonce = sha(Buffer.concat([authData, sha(CHALLENGE)]))

  ssl("req", "-new", "-key", f("leaf.key"), "-subj", `/CN=${keyHash.toString("hex")}/OU=AAA Certification/O=Yard Tests`, "-out", f("leaf.csr"))
  const der = Buffer.concat([Buffer.from([0x30, 0x24, 0xa1, 0x22, 0x04, 0x20]), nonce])
  writeFileSync(f("leaf.ext"), `basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature\n1.2.840.113635.100.8.2=DER:${der.toString("hex").match(/../g).join(":")}\n`)
  ssl("x509", "-req", "-in", f("leaf.csr"), "-CA", f("inter.pem"), "-CAkey", f("inter.key"), "-set_serial", "3", "-days", "36500", "-extfile", f("leaf.ext"), "-out", f("leaf.pem"))

  const toDer = (pem) => new Uint8Array(ssl("x509", "-in", f(pem), "-outform", "DER"))
  const attestation = encodeCBOR(new Map([["fmt", "apple-appattest"], ["attStmt", new Map([["x5c", [toDer("leaf.pem"), toDer("inter.pem")]], ["receipt", new Uint8Array(Buffer.from("test-receipt"))]])], ["authData", new Uint8Array(authData)]]))

  writeFileSync(
    OUT,
    JSON.stringify(
      {
        note: "Generated by scripts/app-attest-fixture.mjs. Test-only keys and CA.",
        appId: APP_ID,
        environment: "development",
        challenge: CHALLENGE,
        keyId: keyHash.toString("base64"),
        attestation: Buffer.from(attestation).toString("base64"),
        rootPem: readFileSync(f("root.pem"), "utf8"),
      },
      null,
      2,
    ) + "\n",
  )
  console.log(`wrote ${OUT}`)
} finally {
  rmSync(dir, { recursive: true, force: true })
}
