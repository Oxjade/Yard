/** Every entry as a row for the `holidays` table, with a stable id per country, date and name. */
export function holidayRows() {
  return (Object.keys(holidays) as (keyof typeof holidays)[]).flatMap((country) =>
    holidays[country].map((h, i) => ({ id: `hol_${country.toLowerCase()}_${h.date.replace(/-/g, "")}_${i}`, country, date: h.date, name: h.name, kind: h.kind ?? "public", estimated: !!h.estimated, source: "config" as const })),
  )
}
